const SINGLE_MAP = {}
for (const tid in SINGLE_BY_TYPE) {
  for (const ch of SINGLE_BY_TYPE[tid]) {
    if (!SINGLE_MAP[ch]) SINGLE_MAP[ch] = []
    if (SINGLE_MAP[ch].indexOf(parseInt(tid)) < 0) SINGLE_MAP[ch].push(parseInt(tid))
  }
}
const TOTAL_MAP = Object.assign({}, WORD_TO_TYPE)
for (const ch in SINGLE_MAP) {
  if (!TOTAL_MAP[ch]) TOTAL_MAP[ch] = SINGLE_MAP[ch]
}

/**
 * 从输入文本中匹配预测类型
 * @param {string} text 用户输入文本
 * @returns {Array<{id:number, count:number, multiCount:number, singleCount:number, len:number, words:Array<string>}>} 按得分降序的类型数组
 */
function matchTypes(text) {
  if (!text) return []
  const hits = {}
  for (const word in TOTAL_MAP) {
    if (!word) continue
    if (text.indexOf(word) >= 0) {
      const isSingle = word.length === 1
      const typeIds = TOTAL_MAP[word]
      for (let i = 0; i < typeIds.length; i++) {
        const tid = typeIds[i]
        if (!hits[tid]) hits[tid] = { id: tid, count: 0, multiCount: 0, singleCount: 0, len: 0, words: [] }
        hits[tid].count += 1
        hits[tid].len += word.length
        hits[tid].words.push(word)
        // 单字命中只做"助攻"：单独分桶计数，不并入主导排序依据
        if (isSingle) hits[tid].singleCount += 1
        else hits[tid].multiCount += 1
      }
    }
  }
  const arr = Object.keys(hits).map(k => hits[k])
  // 排序：多字命中数优先（主导），再比总词长（长词更精确），最后单字命中数只作并列时的助攻
  arr.sort((a, b) => (b.multiCount - a.multiCount) || (b.len - a.len) || (b.singleCount - a.singleCount))
  return arr
}

