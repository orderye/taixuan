def parse_source():
    with open(SRC, "r", encoding="utf-16") as f:
        lines = f.readlines()
    
    shou_data = {}
    current_shou = None
    
    for line in lines:
        line = line.strip()
        if not line:
            continue
        
        # Try to match 首 line: "name：首辞"
        # Check if line starts with a known 首 name followed by ：
        matched = False
        for idx, name in enumerate(SHOU_NAMES):
            shou_num = idx + 1
            patterns = [
                f"{name}：", f"{name}:", f"{name} ",
                f"{name}（", f"{name}(", f"{name}："
            ]
            for pat in patterns:
                if line.startswith(pat):
                    rest = line[len(pat):]
                    rest = re.sub(r'[（(][^）)]*[）)]', '', rest)
                    rest = rest.strip()
                    if rest.endswith('。'):
                        rest = rest[:-1]
                    current_shou = shou_num
                    shou_data[shou_num] = {
                        "name": name,
                        "shou_ci": rest,
                        "zan": []
                    }
                    matched = True
                    break
            if matched:
                break
        
        if current_shou and (line.startswith("初一") or line.startswith("初 一")):
            line = line.replace("初 一", "初一").replace("侧曰", "测曰")
            line = line.replace("次九", "上九")
            zan_positions = ["初一", "次二", "次三", "次四", "次五", "次六", "次七", "次八", "上九"]

            parts = re.split(r'(初一|次二|次三|次四|次五|次六|次七|次八|上九)', line)

            zan_list = []
            i = 0
            while i < len(parts):
                if parts[i] in zan_positions:
                    pos = parts[i]
                    text = parts[i+1] if i+1 < len(parts) else ""
                    i += 2

                    if "测曰：" in text:
                        zan_ci, ce = text.split("测曰：", 1)
                    elif "测曰:" in text:
                        zan_ci, ce = text.split("测曰:", 1)
                    elif "测曰" in text:
                        zan_ci, ce = text.split("测曰", 1)
                    else:
                        zan_ci = text
                        ce = ""

                    zan_ci = zan_ci.strip().rstrip('。').strip()
                    ce = ce.strip().rstrip('。').strip()

                    zan_list.append({
                        "pos": pos,
                        "zan_ci": zan_ci,
                        "ce": ce
                    })
                else:
                    i += 1

            if zan_list:
                shou_data[current_shou]["zan"] = zan_list
    
    return shou_data

def format_shou_meta(num):
    yi = YI_MAP.get(num, "—")
    yi_str = f"准《易》{yi}" if yi != "—" else "无对应《易》卦"
    xuan = XUAN.get(num, "?")
    wu = WUJIA.get(num, "?")
    yy = YINYANG.get(num, "?")
    return f"{xuan} · {yy}家{wu} · {yi_str}"

def generate_shou_section(num, data, annotations):
    name = data["name"]
    shou_ci = data["shou_ci"]
    meta = format_shou_meta(num)
    zan_list = data["zan"]
    
    html = f'  <div class="shou" id="shou-{num}">\n'
    html += f'    <div class="shou-header">\n'
    html += f'      <span class="shou-num">{num:02d}</span>\n'
    html += f'      <span class="shou-name">{name}</span>\n'
    html += f'      <span class="shou-meta">{meta}</span>\n'
    html += f'    </div>\n'
    html += f'    <div class="shou-ci">{shou_ci}</div>\n'
    
    # Zan table
    if zan_list:
        html += f'    <div class="table-wrap">\n'
        html += f'      <table class="zan-table">\n'
        html += f'        <tr><th>赞位</th><th>赞辞</th><th>测曰</th></tr>\n'
        for z in zan_list:
            pos = z["pos"]
            zc = z["zan_ci"]
            ce = z["ce"]
            html += f'        <tr><td class="zan-pos">{pos}</td><td class="zan-text">{zc}</td><td class="zan-ce">{ce}</td></tr>\n'
        html += f'      </table>\n'
        html += f'    </div>\n'
    
    # Annotations
    annot = annotations
    
    # Build annotator tabs
    annotators = []
    for key, label in [("fan", "范望"), ("sima", "司马光"), ("hu", "胡次和"), ("ye", "叶子奇"), ("chen", "陈本礼")]:
        if key in annot and annot[key]:
            annotators.append((key, label))
    
    if annotators:
        html += f'    <div class="annotators" data-shou="{num}">\n'
        for i, (key, label) in enumerate(annotators):
            active = " active" if i == 0 else ""
            html += f'      <span class="annotator-tab{active}" data-target="a{num}-{key}">{label}</span>\n'
        html += f'    </div>\n'
        
        html += f'    <div class="annot-body">\n'
        for i, (key, label) in enumerate(annotators):
            active = " active" if i == 0 else ""
            content = annot[key]
            source_label = {"fan": "范望《太玄经解赞》", "sima": "司马光《集注太玄经》", 
                          "hu": "胡次和《太玄集注》", "ye": "叶子奇《太玄本旨》", 
                          "chen": "陈本礼《太玄阐秘》"}.get(key, "")
            source_loc = {"fan": "识典古籍", "sima": "识典古籍", 
                        "hu": "《永乐大典》辑佚", "ye": "识典古籍（四库本）", 
                        "chen": "识典古籍（聚学轩丛书本）"}.get(key, "")
            
            html += f'      <div class="annot-section{active}" id="a{num}-{key}">\n'
            html += f'        <h4>{source_label}</h4>\n'
            # Split content into quote and gloss
            if isinstance(content, dict):
                if "quote" in content:
                    html += f'        <div class="quote">{content["quote"]}</div>\n'
                if "gloss" in content:
                    html += f'        <div class="gloss">{content["gloss"]}</div>\n'
            else:
                html += f'        <div class="gloss">{content}</div>\n'
            html += f'        <div class="source">辑自{source_loc}</div>\n'
            html += f'      </div>\n'
        html += f'    </div>\n'
    
    html += f'  </div>\n\n'
    return html

